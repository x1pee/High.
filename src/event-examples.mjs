let lastExample = -1,
  lastPhrase = -1,
  lastHint = -1;
const nextIndex = (length, last) => {
  if (last < 0) return Math.floor(Math.random() * length);
  const n = Math.floor(Math.random() * (length - 1));
  return n >= last && last >= 0 ? n + 1 : n;
};
export function entryCopy() {
  lastExample = nextIndex(EVENT_EXAMPLES.length, lastExample);
  lastPhrase = nextIndex(ENTRY_PHRASES.length, lastPhrase);
  lastHint = nextIndex(ENTRY_HINTS.length, lastHint);
  return {
    example: EVENT_EXAMPLES[lastExample].text,
    phrase: ENTRY_PHRASES[lastPhrase],
    hint: ENTRY_HINTS[lastHint],
  };
}
export const EVENT_EXAMPLES = Object.entries(groups).flatMap(
  ([category, texts]) => texts.map((text) => ({ category, text })),
);
export const EXAMPLE_CATEGORIES = Object.keys(groups);
export function findExamples(
  query = "",
  category = "Все",
  entries = EVENT_EXAMPLES,
) {
  const needle = query.trim().toLocaleLowerCase("ru");
  return entries.filter(
    (e) =>
      (category === "Все" || e.category === category) &&
      e.text.toLocaleLowerCase("ru").includes(needle),
  );
}

let previousFirst = null;
export function shuffledExamples(random = Math.random, placeholder = "") {
  const items = [...EVENT_EXAMPLES];
  for (let i = items.length - 1; i > 0; i--) {
    const j = Math.floor(random() * (i + 1));
    [items[i], items[j]] = [items[j], items[i]];
  }
  if (items[0] === previousFirst) items.push(items.shift());
  const repeated = items.findIndex((e) => e.text === placeholder);
  if (repeated >= 0 && repeated < 10) items.push(...items.splice(repeated, 1));
  previousFirst = items[0];
  return items;
}
