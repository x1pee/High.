let last = -1;
export function nextDayExample() {
  let index = Math.floor(Math.random() * DAY_EXAMPLES.length);
  if (index === last) index = (index + 1) % DAY_EXAMPLES.length;
  last = index;
  return DAY_EXAMPLES[index];
}
let promptDeck = [];
let lastPrompt = null;
export function nextDayPrompt() {
  if (!promptDeck.length) {
    promptDeck = [...DAY_PROMPTS];
    for (let i = promptDeck.length - 1; i > 0; i--) {
      const j = Math.floor(Math.random() * (i + 1));
      [promptDeck[i], promptDeck[j]] = [promptDeck[j], promptDeck[i]];
    }
    if (promptDeck.at(-1) === lastPrompt)
      [promptDeck[0], promptDeck[promptDeck.length - 1]] = [
        promptDeck.at(-1),
        promptDeck[0],
      ];
  }
  lastPrompt = promptDeck.pop();
  return lastPrompt;
}
